#!/usr/bin/env node
// Reads the Firebase web config from the web app so both apps always talk to the same project.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, '..', '..', '..', 'modules', 'utilities-sales.js'), 'utf8');
const pick = (k) => { const m = src.match(new RegExp(`${k}:\\s*["']([^"']+)["']`)); if (!m) throw new Error(`firebaseConfig.${k} not found`); return m[1]; };
writeFileSync(join(here, '..', 'lib', 'firebase_config.dart'),
`// GENERATED by tools/gen_config.mjs from modules/utilities-sales.js - do not edit.
// These are the public web identifiers of the Firebase project (not secrets).
import 'package:sarim_core/sarim_core.dart';

const firebaseConfig = FirebaseConfig(apiKey: '${pick('apiKey')}', projectId: '${pick('projectId')}');
`);
console.log('wrote lib/firebase_config.dart');
