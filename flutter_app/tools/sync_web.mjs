#!/usr/bin/env node
// Copies the built web app (../dist) into assets/www and lists every asset directory in pubspec.yaml
// (Flutter does not include sub-directories of an asset folder automatically).
// Usage: node flutter_app/tools/sync_web.mjs [--build]
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const root = join(app, '..');
const dist = join(root, 'dist');
const www = join(app, 'assets', 'www');

if (process.argv.includes('--build') || !existsSync(join(dist, 'index.html'))) {
  execFileSync('node', ['build.js'], { cwd: root, stdio: 'inherit' });
}

rmSync(www, { recursive: true, force: true });
cpSync(dist, www, { recursive: true });
// The service worker and its build metadata are not used inside the app (native mode unregisters service workers).
rmSync(join(www, 'meta.json'), { force: true });

const dirs = [];
(function walk(dir) {
  dirs.push(relative(app, dir).split('\\').join('/') + '/');
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p);
  }
})(www);

const pubspecPath = join(app, 'pubspec.yaml');
const pubspec = readFileSync(pubspecPath, 'utf8');
const block = ['    # BEGIN WEB ASSETS (generated by tools/sync_web.mjs - do not edit)', ...dirs.map((d) => `    - ${d}`), '    # END WEB ASSETS'].join('\n');
const next = pubspec.replace(/ {4}# BEGIN WEB ASSETS[\s\S]*# END WEB ASSETS/, block);
if (next === pubspec && !pubspec.includes(block)) throw new Error('Could not find the WEB ASSETS markers in pubspec.yaml');
writeFileSync(pubspecPath, next);
console.log(`Synced ${dirs.length} asset folder(s) into ${relative(root, www)}`);
